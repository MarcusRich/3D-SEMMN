"""BioSemi-128 to 10-20 mapping, and the starter-hardware montages simulated in P3.

BioSemi's 128-channel "ABCD" cap is a radial-equidistant layout on a sphere. The 10-20
targets use the BESA spherical convention (theta from the vertex, phi azimuth). Both are
idealised spherical positions, so the nearest BioSemi electrode is found by angle on the
unit sphere. ``BIOSEMI_1020`` was generated by ``nearest_biosemi`` from MNE-Python's
``biosemi128`` positions; ``tests/test_eeg_montages.py`` regenerates it when MNE is
installed. It agrees with BioSemi's published equivalents (Cz = A1, Pz = A19, Oz = A23,
Fz = C21, C3 = D19, C4 = B22, O1 = A15, O2 = A28).

Channel columns in the data are assumed to be in cap order A1..A32, B1..B32, C1..C32,
D1..D32 (index 0..127).

Starter montages (vendor default electrode positions):
- OpenBCI Cyton, 8 channels (Ultracortex Mark IV default): Fp1 Fp2 C3 C4 P7 P8 O1 O2.
- OpenBCI Cyton + Daisy, 16 channels: the 8 above plus F7 F8 F3 F4 T7 T8 P3 P4.
- g.tec Unicorn Hybrid Black, 8 channels (fixed): Fz C3 Cz C4 Pz PO7 Oz PO8.

The simulation keeps BioSemi's gel signal quality at those positions, so it is an upper
bound on what the starter device would record (dry or saline electrodes add noise).
"""

from __future__ import annotations

import numpy as np

# 10-20 name -> (theta, phi) in degrees, BESA spherical convention.
BESA_1020: dict[str, tuple[float, float]] = {
    "Fp1": (-92, -72), "Fp2": (92, 72), "F7": (-92, -36), "F3": (-60, -51), "Fz": (46, 90),
    "F4": (60, 51), "F8": (92, 36), "T7": (-92, 0), "C3": (-46, 0), "Cz": (0, 0),
    "C4": (46, 0), "T8": (92, 0), "P7": (-92, 36), "P3": (-60, 51), "Pz": (46, -90),
    "P4": (60, -51), "P8": (92, -36), "PO7": (-92, 54), "PO8": (92, -54), "O1": (-92, 72),
    "Oz": (92, -90), "O2": (92, -72),
}

# 10-20 name -> nearest BioSemi-128 electrode (generated; see module docstring).
BIOSEMI_1020: dict[str, str] = {
    "Fp1": "C29", "Fp2": "C16", "F7": "D7", "F3": "D4", "Fz": "C21", "F4": "C4",
    "F8": "C7", "T7": "D23", "C3": "D19", "Cz": "A1", "C4": "B22", "T8": "B26",
    "P7": "D31", "P3": "A7", "Pz": "A19", "P4": "B4", "P8": "B11", "PO7": "A10",
    "PO8": "B7", "O1": "A15", "Oz": "A23", "O2": "A28",
}

STARTER_MONTAGES: dict[str, tuple[str, ...]] = {
    "cyton8": ("Fp1", "Fp2", "C3", "C4", "P7", "P8", "O1", "O2"),
    "cyton_daisy16": (
        "Fp1", "Fp2", "C3", "C4", "P7", "P8", "O1", "O2",
        "F7", "F8", "F3", "F4", "T7", "T8", "P3", "P4",
    ),
    "unicorn8": ("Fz", "C3", "Cz", "C4", "Pz", "PO7", "Oz", "PO8"),
}

# Centro-parietal N400 region, fixed per montage before looking at any N400 data.
N400_ROI_1020: dict[str, tuple[str, ...]] = {
    "cyton8": ("C3", "C4"),
    "cyton_daisy16": ("C3", "C4", "P3", "P4"),
    "unicorn8": ("C3", "Cz", "C4", "Pz"),
}

# 128-channel N400 region: BioSemi electrodes within this angle of CPz (between Cz and Pz).
N400_ROI_RADIUS_DEG = 30.0

BIOSEMI_NAMES: tuple[str, ...] = tuple(f"{b}{i}" for b in "ABCD" for i in range(1, 33))


def biosemi_index(name: str) -> int:
    """Column index (0..127) of a BioSemi-128 electrode name such as ``"C21"``."""
    return BIOSEMI_NAMES.index(name)


def montage_indices(montage: str) -> np.ndarray:
    """Column indices into the 128-channel data for a starter montage."""
    return np.array([biosemi_index(BIOSEMI_1020[n]) for n in STARTER_MONTAGES[montage]])


def sph_to_unit(theta_deg: float, phi_deg: float) -> np.ndarray:
    """BESA (theta, phi) degrees to a unit vector (x right, y anterior, z up)."""
    t, p = np.radians(theta_deg), np.radians(phi_deg)
    return np.array([np.sin(t) * np.cos(p), np.sin(t) * np.sin(p), np.cos(t)])


def nearest_biosemi(positions: dict[str, np.ndarray]) -> dict[str, str]:
    """Nearest BioSemi electrode (by angle) for each 10-20 target in ``BESA_1020``.

    ``positions`` maps BioSemi names to 3-D positions about the sphere centre.
    """
    names = list(positions)
    b = np.array([positions[n] for n in names], dtype=float)
    b /= np.linalg.norm(b, axis=1, keepdims=True)
    out = {}
    for target, (t, p) in BESA_1020.items():
        out[target] = names[int(np.argmax(b @ sph_to_unit(t, p)))]
    return out


def n400_roi_128(positions: dict[str, np.ndarray]) -> np.ndarray:
    """Indices of BioSemi electrodes within ``N400_ROI_RADIUS_DEG`` of CPz."""
    cpz = sph_to_unit(23, -90)
    idx = []
    for i, name in enumerate(BIOSEMI_NAMES):
        v = np.asarray(positions[name], dtype=float)
        ang = np.degrees(np.arccos(np.clip(v @ cpz / np.linalg.norm(v), -1, 1)))
        if ang <= N400_ROI_RADIUS_DEG:
            idx.append(i)
    return np.array(idx)


def n400_roi_indices(montage: str) -> np.ndarray:
    """Indices into the 128-channel data of a starter montage's N400 region."""
    return np.array([biosemi_index(BIOSEMI_1020[n]) for n in N400_ROI_1020[montage]])


def biosemi_positions() -> dict[str, np.ndarray]:
    """BioSemi-128 positions from MNE-Python (needs ``mne``)."""
    import mne  # local import: only montage generation and scalp summaries need it

    return mne.channels.make_standard_montage("biosemi128").get_positions()["ch_pos"]


def scalp_region(pos: np.ndarray) -> str:
    """Coarse region name of a unit-sphere position: frontal/central/parietal/occipital
    crossed with left/midline/right, or temporal for low lateral positions."""
    x, y, z = pos / np.linalg.norm(pos)
    side = "L" if x < -0.25 else ("R" if x > 0.25 else "mid")
    if abs(x) > 0.75 and abs(y) < 0.5:
        return f"temporal-{side}"
    if y > 0.35:
        ap = "frontal"
    elif y > -0.2:
        ap = "central"
    elif y > -0.75:
        ap = "parietal"
    else:
        ap = "occipital"
    return f"{ap}-{side}"
